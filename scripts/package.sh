#!/usr/bin/env bash
# Build release binaries and package them for people without a Rust toolchain:
#   dist/lablink-<version>-x86_64-linux.tar.gz   per-user install, no root
#   dist/lablink_<version>_amd64.deb             Ubuntu 20.04+ / Debian 11+
#   dist/SHA256SUMS, dist/BUILDINFO
#
# Release builds go through scripts/release.sh, which runs this script in the
# pinned Ubuntu 20.04 container on a clean checkout of one commit. Running it
# directly builds from the working tree (development only).
#
# Environment:
#   LABLINK_GIT_SHA      commit embedded in the binaries (default: git HEAD)
#   LABLINK_MAINTAINER   Debian Maintainer field (default: the project maintainer)
#   LABLINK_HOMEPAGE     Debian Homepage field (default: the project repository)
#   LABLINK_MAX_GLIBC    refuse binaries needing a newer glibc (default 2.31)
set -euo pipefail
cd "$(dirname "$0")/.."

version=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)
arch=$(dpkg --print-architecture 2>/dev/null || echo amd64)
sha=${LABLINK_GIT_SHA:-$(git rev-parse HEAD 2>/dev/null || echo unknown)}
if [ -z "${LABLINK_GIT_SHA:-}" ] && [ -n "$(git status --porcelain 2>/dev/null)" ]; then
    sha="$sha-dirty"
fi
maintainer=${LABLINK_MAINTAINER:-"Yusuf Guenena <253617803+yusufdxb@users.noreply.github.com>"}
homepage=${LABLINK_HOMEPAGE:-https://github.com/yusufdxb/lablink}
# Reproducible archives: every timestamp is the commit time (scripts/release.sh
# passes it), so rebuilding a commit gives byte-identical artifacts.
export SOURCE_DATE_EPOCH=${SOURCE_DATE_EPOCH:-$(git log -1 --format=%ct HEAD 2>/dev/null || echo 0)}
max_glibc=${LABLINK_MAX_GLIBC:-2.31}

# The third-party notices must describe exactly this dependency set.
want=$(sha256sum Cargo.lock | cut -d' ' -f1)
grep -q "Cargo.lock sha256: $want" THIRD_PARTY_LICENSES.md || {
    echo "package: THIRD_PARTY_LICENSES.md is stale; run scripts/third-party.sh" >&2
    exit 1
}

echo "== building lablink $version ($sha) for $arch"
LABLINK_GIT_SHA=$sha cargo build --release --workspace --locked
rel=target/release
bins="$rel/lablink $rel/lablinkd $rel/lablink-gui"
for b in $bins; do test -x "$b"; done

# Highest GLIBC symbol version any binary needs: the minimum libc6.
# shellcheck disable=SC2086
glibc=$(objdump -T $bins | grep -o 'GLIBC_[0-9.]*' | sed 's/GLIBC_//' | sort -uV | tail -1)
echo "== minimum glibc: $glibc (limit $max_glibc)"
if [ "$(printf '%s\n%s\n' "$glibc" "$max_glibc" | sort -V | tail -1)" != "$max_glibc" ]; then
    echo "package: binaries need glibc $glibc, newer than the supported baseline $max_glibc" >&2
    exit 1
fi
reported=$("$rel/lablink" version | head -1)
[ "$reported" = "lablink $version (commit $sha)" ] || {
    echo "package: 'lablink version' says '$reported', expected 'lablink $version (commit $sha)'" >&2
    exit 1
}

rm -rf dist && mkdir -p dist
# Every icon comes from packaging/lablink.svg (scripts/build-icons.sh).
scripts/build-icons.sh --check
install_pngs() {
    for s in 16 24 32 48 64 128 256 512; do
        install -D -m 644 "packaging/icons/lablink-$s.png" "$1/${s}x$s/apps/lablink.png"
    done
}
doc_files="README.md LICENSE NOTICE THIRD_PARTY_LICENSES.md CHANGELOG.md SECURITY.md config/example.yaml"

# ---- tarball (per-user install, no root) -----------------------------------
t=dist/lablink-$version-x86_64-linux
mkdir -p "$t/bin" "$t/share/applications" "$t/share/icons/hicolor/scalable/apps" \
    "$t/share/doc/lablink" "$t/share/bash-completion/completions"
install -m 755 $bins "$t/bin/"
install -m 644 packaging/lablink-gui.desktop "$t/share/applications/"
install -m 644 packaging/lablink.svg "$t/share/icons/hicolor/scalable/apps/"
install_pngs "$t/share/icons/hicolor"
"$rel/lablink" completions bash > "$t/share/bash-completion/completions/lablink"
install -m 755 packaging/install.sh packaging/uninstall.sh "$t/"
# shellcheck disable=SC2086
install -m 644 $doc_files "$t/share/doc/lablink/"
cp -r docs "$t/share/doc/lablink/"
install -m 644 LICENSE "$t/LICENSE"
find "$t" -type d -exec chmod 755 {} +
find "$t" -type f ! -perm -u+x -exec chmod 644 {} +
tar --owner=0 --group=0 --numeric-owner --sort=name --mtime="@$SOURCE_DATE_EPOCH" \
    -C dist -czf "$t.tar.gz" "$(basename "$t")"
rm -rf "$t"

# ---- .deb -------------------------------------------------------------------
d=dist/deb
mkdir -p "$d/DEBIAN" "$d/usr/bin" "$d/usr/lib/systemd/user" \
    "$d/usr/share/bash-completion/completions" "$d/usr/share/applications" \
    "$d/usr/share/icons/hicolor/scalable/apps" "$d/usr/share/doc/lablink"
install -m 755 $bins "$d/usr/bin/"
# The unit is generated by the same code as `lablink install-service`.
"$rel/lablink" install-service --print --daemon-path /usr/bin/lablinkd > "$d/usr/lib/systemd/user/lablinkd.service"
cmp "$d/usr/lib/systemd/user/lablinkd.service" packaging/lablinkd.service
"$rel/lablink" completions bash > "$d/usr/share/bash-completion/completions/lablink"
install -m 644 packaging/lablink-gui.desktop "$d/usr/share/applications/"
install -m 644 packaging/lablink.svg "$d/usr/share/icons/hicolor/scalable/apps/"
install_pngs "$d/usr/share/icons/hicolor"
# shellcheck disable=SC2086
install -m 644 $doc_files "$d/usr/share/doc/lablink/"
cat > "$d/usr/share/doc/lablink/copyright" <<COPYRIGHT
Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/
Upstream-Name: LabLink
Source: https://github.com/yusufdxb/lablink

Files: *
Copyright: The LabLink Authors (see NOTICE)
License: Apache-2.0
 The full text is in /usr/share/doc/lablink/LICENSE. Third-party components
 compiled into the binaries, and their licenses, are listed in
 /usr/share/doc/lablink/THIRD_PARTY_LICENSES.md.
COPYRIGHT
chmod 644 "$d/usr/lib/systemd/user/lablinkd.service" "$d/usr/share/bash-completion/completions/lablink" \
    "$d/usr/share/doc/lablink/copyright"
size=$(du -sk "$d/usr" | cut -f1)
{
    echo "Package: lablink"
    echo "Version: $version"
    echo "Architecture: $arch"
    echo "Maintainer: $maintainer"
    echo "Installed-Size: $size"
    echo "Depends: libc6 (>= $glibc), libgcc-s1, openssh-client, libgl1, libegl1, libxkbcommon0, libxkbcommon-x11-0, libx11-6, libx11-xcb1, libxcursor1, libxrandr2, libxi6, libwayland-client0, libwayland-egl1"
    echo "Recommends: bash-completion"
    echo "Section: net"
    echo "Priority: optional"
    echo "Homepage: $homepage"
    cat <<'DESC'
Description: find lab machines and robots and SSH to them by name
 LabLink is a small per-user daemon (lablinkd), CLI (lablink) and desktop
 app (lablink-gui). It discovers hosts only on networks you allow, tracks
 devices by SSH host-key identity rather than IP address, refuses changed
 host keys, monitors reachability, SSH and login health, and runs read-only
 health checks. Sites (labs, offices, workshops) keep devices of places you
 are not at out of the way. It uses your OpenSSH client and stores no
 passwords.
 .
 After installing, run 'lablink init' or open LabLink from the menu.
DESC
} > "$d/DEBIAN/control"
cat > "$d/DEBIAN/postinst" <<'POSTINST'
#!/bin/sh
set -e
echo "LabLink installed. Each user runs 'lablink init' (or opens LabLink) to name their site, choose networks and start their own lablinkd."
exit 0
POSTINST
cat > "$d/DEBIAN/prerm" <<'PRERM'
#!/bin/sh
set -e
# Stop only instances of this package, preserving per-user tarball installs.
# Each user's configuration and state in their home directory are kept
# (also on purge): delete ~/.config/lablink and ~/.local/state/lablink to
# remove them.
if [ "$1" = remove ]; then
    for executable in /proc/[0-9]*/exe; do
        case "$(readlink "$executable" 2>/dev/null || true)" in
            /usr/bin/lablinkd|'/usr/bin/lablinkd (deleted)')
                pid=${executable#/proc/}; pid=${pid%/exe}
                kill -TERM "$pid" 2>/dev/null || true
                ;;
        esac
    done
fi
exit 0
PRERM
chmod 755 "$d/DEBIAN/postinst" "$d/DEBIAN/prerm"
find "$d" -type d -exec chmod 755 {} +
(cd "$d" && find usr -type f -exec md5sum {} + | sort -k2 > DEBIAN/md5sums)
# dpkg-deb uses SOURCE_DATE_EPOCH for the ar members; older dpkg does not
# clamp file times inside data.tar, so set them all here.
find "$d" -exec touch -h -d "@$SOURCE_DATE_EPOCH" {} +
dpkg-deb --root-owner-group -Zxz --build "$d" "dist/lablink_${version}_${arch}.deb" >/dev/null
rm -rf "$d"

# ---- build record -------------------------------------------------------------
{
    echo "lablink $version"
    echo "commit: $sha"
    echo "rustc: $(rustc --version)"
    echo "cargo: $(cargo --version)"
    echo "build image: ${LABLINK_BASE_IMAGE:-host $(. /etc/os-release && echo "$PRETTY_NAME")}"
    echo "minimum glibc: $glibc"
    echo "SOURCE_DATE_EPOCH: $SOURCE_DATE_EPOCH"
    echo "dynamic libraries:"
    for b in $bins; do
        echo "  $(basename "$b"): $(objdump -p "$b" | awk '/NEEDED/ {print $2}' | paste -sd ' ' -)"
    done
} > dist/BUILDINFO
(cd dist && sha256sum ./*.tar.gz ./*.deb ./BUILDINFO > SHA256SUMS)
echo "== artifacts"
ls -l dist
cat dist/BUILDINFO
dpkg-deb --info "dist/lablink_${version}_${arch}.deb" | sed -n '/Package:/,/Description:/p'
